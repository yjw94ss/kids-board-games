import { readFile, writeFile } from 'node:fs/promises';
// One classic script removes module-graph fetches and runs on older browsers.
const files=['board-data.js','engine.js','app.js'];
const parts=await Promise.all(files.map(async file=>{
  const source=await readFile(new URL(`../${file}`,import.meta.url),'utf8');
  return `// ${file}\n${source.replace(/^import .*;\n/gm,'').replace(/^export /gm,'')}`;
}));
const output=`// Generated by npm run build. Edit the source files instead.\n(function () {\n'use strict';\ntry {\n${parts.join('\n\n')}\n} catch (error) {\nconsole.error('Game initialization failed:',error);\nif (window.showGameLoadError) window.showGameLoadError();\n}\n})();\n`;
await writeFile(new URL('../game.js',import.meta.url),output);
console.log('Built game.js (single browser script)');
